// Polite, bounded inventory crawl of the Coral console, once without login and once with
// the product's own guest mode. Same-origin only, a delay between pages and a hard page cap;
// it records each route's status, redirect, title and a text digest, and follows in-app links
// one hop to surface routes we had not listed. It does NOT probe hidden/privileged endpoints.
//
// Usage: node scripts/coral/crawl-inventory.mjs
// Output: runs/coral/crawl/<pass>/<slug>.{txt,png} and runs/coral/inventory.md
import { writeFileSync, mkdirSync } from 'fs';
import path from 'path';
import { loadChromium, OUT, CORAL } from './lib/pw.mjs';

const DELAY_MS = 700;        // be gentle with the server
const MAX_PAGES = 45;        // hard cap per pass
const SEED = ['/', '/login', '/pos', '/pos/virtual', '/orders', '/networks', '/wallets',
  '/tokens', '/stablecoins', '/environments', '/environments/new', '/security', '/sdk', '/docs'];

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const slug = (p) => (p === '/' ? 'root' : p.replace(/^\/+/, '').replace(/[^\w.-]+/g, '_')) || 'root';

async function crawl(page, label, loggedIn) {
  const dir = path.join(OUT, 'crawl', label);
  mkdirSync(dir, { recursive: true });
  const queue = [...SEED];
  const seen = new Set();
  const rows = [];

  while (queue.length && rows.length < MAX_PAGES) {
    const route = queue.shift();
    if (seen.has(route)) continue;
    seen.add(route);

    let status = 0, finalPath = route, title = '', note = '';
    try {
      const resp = await page.goto(CORAL + route, { waitUntil: 'networkidle', timeout: 25000 });
      status = resp ? resp.status() : 0;
      finalPath = new URL(page.url()).pathname;
      title = (await page.title()).replace(/\s*\|\s*NetX.*/i, '').trim();
      const text = (await page.evaluate(() => document.body.innerText)).replace(/\n{2,}/g, '\n').trim();
      writeFileSync(path.join(dir, slug(route) + '.txt'), `# ${route} -> ${finalPath} (HTTP ${status})\n\n${text}`);
      await page.screenshot({ path: path.join(dir, slug(route) + '.png'), fullPage: true }).catch(() => {});

      if (finalPath !== route) note = `redirects to ${finalPath}`;
      else if (/Backend not connected|Not activated|wired into the application shell/i.test(text)) {
        note = /wired into the application shell/i.test(text) ? 'placeholder stub' : 'gated / not activated';
      }

      // discover same-origin in-app links, one hop
      const links = await page.evaluate(() =>
        Array.from(document.querySelectorAll('a[href^="/"]')).map((a) => a.getAttribute('href')));
      for (const l of links) {
        const clean = l.split('#')[0].split('?')[0];
        if (clean && !seen.has(clean) && !queue.includes(clean) && !/\.(png|jpg|svg|css|js|ico)$/i.test(clean)) {
          queue.push(clean);
        }
      }
    } catch (e) {
      note = 'error: ' + String(e.message || e).slice(0, 60);
    }
    rows.push({ route, status, finalPath, title, note });
    console.log(`[${label}] ${String(status).padEnd(3)} ${route}${note ? '  (' + note + ')' : ''}`);
    await sleep(DELAY_MS);
  }
  return rows;
}

const chromium = await loadChromium();
const browser = await chromium.launch({ args: ['--no-sandbox'] });

// Pass 1: no login (fresh context, no cookies)
const anon = await browser.newContext({ viewport: { width: 1280, height: 1400 } });
const anonRows = await crawl(await anon.newPage(), 'anon', false);
await anon.close();

// Pass 2: guest login via the product's own button
const auth = await browser.newContext({ viewport: { width: 1280, height: 1400 } });
const gp = await auth.newPage();
await gp.goto(`${CORAL}/login`, { waitUntil: 'networkidle' });
await gp.getByText('Continue as Guest', { exact: false }).first().click();
await gp.waitForURL((u) => !u.pathname.includes('/login'), { timeout: 30000 }).catch(() => {});
const guestRows = await crawl(gp, 'guest', true);
await auth.close();
await browser.close();

// Inventory markdown
const table = (rows) => ['| Route | HTTP | Resolved | Title | Note |', '|---|---|---|---|---|',
  ...rows.map((r) => `| \`${r.route}\` | ${r.status} | ${r.finalPath === r.route ? '—' : '`' + r.finalPath + '`'} | ${r.title || '—'} | ${r.note || '—'} |`)].join('\n');
const md = `# Coral route inventory (crawl)\n\nGenerated by \`scripts/coral/crawl-inventory.mjs\`. Same-origin, ${DELAY_MS}ms between pages, cap ${MAX_PAGES}/pass. Pages/text/screenshots under \`runs/coral/crawl/\` (gitignored).\n\n## Anonymous (no login)\n\n${table(anonRows)}\n\n## Guest (product's own guest mode)\n\n${table(guestRows)}\n`;
writeFileSync(path.join(OUT, 'inventory.md'), md);
console.log(`\nanon: ${anonRows.length} pages, guest: ${guestRows.length} pages -> ${path.join(OUT, 'inventory.md')}`);
